export const LANGS = [...navigator.languages, 'en'].map((l) => l.toLowerCase());
const lang = LANGS.map((l) => l.split('-')[0]).find((l) => STRINGS[l]) ?? 'en';
document.documentElement.lang = lang;

export function t(key) {
  return STRINGS[lang][key] ?? STRINGS.en[key] ?? key;
}

/** Picks a localized string from a manifest messages entry ({es: ..., en: ...}). */
export function pick(messages) {
  if (!messages) return undefined;
  for (const l of LANGS) {
    if (messages[l]) return messages[l];
    const base = l.split('-')[0];
    if (messages[base]) return messages[base];
  }
  return Object.values(messages)[0];
}

const rtf = new Intl.RelativeTimeFormat(lang, { numeric: 'auto' });

export function ago(iso) {
  if (!iso) return t('never');
  const s = (new Date(iso).getTime() - Date.now()) / 1000;
  const abs = Math.abs(s);
  if (abs < 60) return rtf.format(Math.round(s), 'second');
  if (abs < 3600) return rtf.format(Math.round(s / 60), 'minute');
  if (abs < 86400) return rtf.format(Math.round(s / 3600), 'hour');
  return rtf.format(Math.round(s / 86400), 'day');
}
